#!/usr/bin/env python3
"""Regenerate the contents page and list of figures inside 00_front_matter.md.

Same rule as figures/fig_4_1_current_state.py: the artifact and the thing that describes it
come from one source, so they cannot drift. Chapters are edited constantly during Stage 5;
a hand-maintained contents page would be wrong within a session and nothing would say so.

Run from v2/:  python3 report/toc.py [--check]

--check exits non-zero if the file on disk is not what this script would write, so a stale
contents page fails loudly instead of being read past.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPORT = Path(__file__).resolve().parent
FRONT = REPORT / "00_front_matter.md"
REFS = "09_references.md"

TOC_OPEN, TOC_CLOSE = "<!-- toc:start -->", "<!-- toc:end -->"
FIG_OPEN, FIG_CLOSE = "<!-- figures:start -->", "<!-- figures:end -->"

# Where each figure is inserted, and the caption's first clause. Kept here rather than parsed
# because the captions are block quotes several lines long and the list wants one line each.
FIGURES = [
    ("4.1", "04_threat_model.md", "Home Assistant as it stands today, with the six trust "
     "boundaries of §4.6 overlaid; four of the six do not exist", "figures/fig_4_1_current_state.py"),
    ("5.1", "05_architecture.md", "The same system with the design of Chapter 5 applied, drawn "
     "on Figure 4.1's canvas", "figures/fig_5_1_confined.py"),
]


def chapters() -> list[Path]:
    found = sorted(p for p in REPORT.glob("0[1-8]_*.md"))
    if len(found) != 8:
        raise SystemExit(f"expected 8 chapter files, found {len(found)}: "
                         f"{[p.name for p in found]}")
    return found


def build_toc() -> str:
    lines = ["| | Section | |", "|---|---|---|"]
    for path in chapters():
        text = path.read_text().split("\n")
        title = text[0].lstrip("# ").strip()
        lines.append(f"| | **{title}** | `{path.name}` |")
        # Everything after the final "## References" pointer is back matter, not a section.
        body = "\n".join(text)
        cut = body.rfind("\n## References")
        body = body[:cut] if cut > 0 else body
        for line in body.split("\n"):
            if line.startswith("## "):
                heading = line[3:].strip()
                num, _, rest = heading.partition(" ")
                lines.append(f"| {num} | {rest} | |")
    lines.append(f"| | **References** | `{REFS}` |")
    return "\n".join(lines)


def build_figures() -> str:
    lines = ["| Figure | Subject | In | Generated by |", "|---|---|---|---|"]
    for num, where, caption, script in FIGURES:
        lines.append(f"| **{num}** | {caption} | `{where}` | `{script}` |")
    return "\n".join(lines)


def check_counts(text: str) -> list[str]:
    """The contents note states two counts about the chapters. Verify, don't trust.

    Both are the kind of number that is right when written and wrong a week later, and
    nothing in a markdown file says so. §6.4.5's rule applied to prose: a claim that has
    no instrument checking it is a claim that will drift.
    """
    l3 = tables = 0
    for path in chapters():
        for line in path.read_text().split("\n"):
            if line.startswith("### "):
                l3 += 1
            elif re.match(r"^\|[\s-]*-{3}", line):   # a markdown table's separator row
                tables += 1
    problems = []
    stated_l3 = re.search(r"headings — (\d+) of them — are omitted", text)
    # Three tables are numbered (see the Tables section); the prose states the rest.
    tables_section = text.split("## Tables", 1)[-1]
    numbered = len(re.findall(r"^\| \*\*\d+\.\d+\*\* \|", tables_section, re.M))
    m = re.search(r"other (\d+) tables are deliberately unnumbered", text)
    stated_tb = None
    if m and numbered:
        total = int(m.group(1)) + numbered
        stated_tb = re.match(r"(\d+)", str(total))
    if not stated_l3 or int(stated_l3.group(1)) != l3:
        problems.append(f"third-level headings: prose says "
                        f"{stated_l3.group(1) if stated_l3 else '?'}, chapters have {l3}")
    if not stated_tb or int(stated_tb.group(1)) != tables:
        problems.append(f"tables: prose says "
                        f"{stated_tb.group(1) if stated_tb else '?'}, chapters have {tables}")
    return problems


def splice(text: str, open_m: str, close_m: str, block: str) -> str:
    i, j = text.index(open_m), text.index(close_m)
    return text[: i + len(open_m)] + "\n\n" + block + "\n\n" + text[j:]


def main() -> int:
    text = FRONT.read_text()
    out = splice(text, TOC_OPEN, TOC_CLOSE, build_toc())
    out = splice(out, FIG_OPEN, FIG_CLOSE, build_figures())
    problems = check_counts(out)
    for p in problems:
        print(f"STALE COUNT: {p}", file=sys.stderr)
    if "--check" in sys.argv:
        if problems:
            return 1
        if out != text:
            print("STALE: 00_front_matter.md's contents page does not match the chapters. "
                  "Run: python3 report/toc.py", file=sys.stderr)
            return 1
        print("contents page is current")
        return 0
    FRONT.write_text(out)
    n = out.count("\n| ") - out.count("\n|---")
    print(f"wrote {FRONT.name}: {len(chapters())} chapters, "
          f"{len(FIGURES)} figures, {n} contents rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
